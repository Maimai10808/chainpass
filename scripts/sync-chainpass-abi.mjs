import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = resolve(
  repositoryRoot,
  "contracts/out/ChainPass.sol/ChainPass.json",
);
const outputPath = resolve(
  repositoryRoot,
  "packages/web3/src/chainpass-abi.ts",
);

const artifact = JSON.parse(await readFile(artifactPath, "utf8"));

if (!Array.isArray(artifact.abi)) {
  throw new Error(`ChainPass ABI is missing from ${artifactPath}`);
}

const source =
  `// Generated by pnpm web3:sync-abi after forge build.\n` +
  `// Do not edit this ABI by hand.\n` +
  `export const chainPassAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

await writeFile(outputPath, source, "utf8");
console.log(`Synced ChainPass ABI to ${outputPath}`);
